#!/usr/bin/env node
// CNT-901 and CNT-902: audits every live activity card for seated, bedside and
// large-grip coverage. Prints a Markdown report; `--write` saves it to
// docs/specs/global/card-audit.md. Node 24 strips the TypeScript types on import.
// Usage: node scripts/card-audit.mjs [--write]
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { auditCards } from '../src/lib/card-audit.ts';
import { readCards } from './content-bundle.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const REPORT_PATH = resolve(here, '../../docs/specs/global/card-audit.md');
const AUDIT_DATE = '2026-11-21';

const CHECKS = [
  ['noSeatedSetting', 'Missing the `seated` setting'],
  ['noBedsideOrVariation', 'Missing the `bedside` setting and any `bedside` variation'],
  ['noLargeGrip', 'No `large-grip` variation'],
  ['noSeatedVariation', 'No `seated` variation'],
];

/** The Markdown report. Lists the card ids for each check, so a reviewer can open them directly. */
export function renderReport(report, names) {
  const lines = [
    '# Card audit: seated, bedside and large-grip coverage',
    '',
    `Dated ${AUDIT_DATE}. Generated by \`site/scripts/card-audit.mjs\` (\`pnpm audit:cards\`) for CNT-901 and CNT-902.`,
    '',
    'An occupational therapist or nurse still reviews the adaptations before they are relied on; this audit only shows where they are missing. Withdrawn cards are left out.',
    '',
    `Cards read: ${report.total}. Live cards audited: ${report.live}.`,
    '',
    '| Check | Cards failing | Share of live cards |',
    '|---|---:|---:|',
  ];
  for (const [key, label] of CHECKS) {
    const count = report.failures[key].length;
    const share = report.live ? Math.round((count / report.live) * 100) : 0;
    lines.push(`| ${label} | ${count} | ${share}% |`);
  }
  for (const [key, label] of CHECKS) {
    const ids = report.failures[key];
    lines.push('', `## ${label}`, '');
    if (ids.length === 0) {
      lines.push('None.');
      continue;
    }
    for (const id of ids) lines.push(`- \`${id}\`${names.get(id) ? `: ${names.get(id)}` : ''}`);
  }
  return `${lines.join('\n')}\n`;
}

function main(args) {
  const cards = readCards();
  const report = auditCards(cards);
  const names = new Map(cards.map((c) => [c.id, c.data.name]));
  const text = renderReport(report, names);
  if (args.includes('--write')) {
    writeFileSync(REPORT_PATH, text);
    console.log(`card-audit: wrote ${REPORT_PATH}`);
  }
  for (const [key, label] of CHECKS) console.log(`${label}: ${report.failures[key].length} of ${report.live}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main(process.argv.slice(2));
}
